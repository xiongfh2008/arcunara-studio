// RC14: render an opt-in GitHub Actions workflow without ever handling
// GitHub OAuth credentials or storing a deploy key in the project metadata.
// The Arcunara composite action is pinned to a reviewed immutable commit.
import { ApiError } from "./httputil.mjs";

export const PINNED_ACTION_SHA = "0f61b040694502d0c7a13be78f1ab5b845335b36";
const UUID_RE = /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/;
const OUTPUTS = new Set(["dist","build","out","public"]);
const BUILD_MODES = new Set(["npm","none"]);

export function generateGithubWorkflow({projectId, outputDir="dist", buildMode="npm"}) {
  if (!UUID_RE.test(projectId)) {
    throw new ApiError(400,"Invalid project id","INVALID_PROJECT_ID");
  }
  if (!OUTPUTS.has(outputDir)) {
    throw new ApiError(400,"Unsupported static output directory","INVALID_OUTPUT_DIR");
  }
  if (!BUILD_MODES.has(buildMode)) {
    throw new ApiError(400,"Invalid build mode","INVALID_BUILD_MODE");
  }
  const secret = (name) => "$" + "{{ secrets." + name + " }}";
  const buildSteps = buildMode === "npm"
    ? `      - name: Set up Node for local build
        uses: actions/setup-node@v4
        with:
          node-version: "24"
          cache: npm
      - name: Install project dependencies
        run: npm ci
      - name: Build static website
        run: npm run build
`
    : "";
  const content = `# Generated by Arcunara Studio RC14. Requires repository secrets:
# ARCU_API_BASE (authorized and reachable HTTPS API endpoint)
# ARCU_DEPLOY_KEY (project-scoped key; never commit its actual value)
# Build scripts execute only in the website repository's GitHub runner.
name: Arcunara static publish
on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: arcunara-publish
  cancel-in-progress: false

jobs:
  publish:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout website
        uses: actions/checkout@v4
${buildSteps}      - name: Publish prebuilt assets to Arcunara
        uses: xiongfh2008/arcunara-studio@${PINNED_ACTION_SHA}
        with:
          api-base: ${secret("ARCU_API_BASE")}
          project-id: "${projectId}"
          deploy-key: ${secret("ARCU_DEPLOY_KEY")}
          output-dir: "${outputDir}"
`;
  return {
    fileName:"arcunara-deploy.yml",
    content,
    outputDir,
    buildMode,
    requiredSecrets:["ARCU_API_BASE","ARCU_DEPLOY_KEY"],
    actionCommit:PINNED_ACTION_SHA
  };
}
